//!
//! This is a tooling boundary: it reads `scenarios/*.ron` through the canonical
//! `ScenarioDef` loader and emits a deterministic markdown snapshot. It reports
//! structural activation only; it does not claim that a scenario golden proved
//! the intended causal branch.

