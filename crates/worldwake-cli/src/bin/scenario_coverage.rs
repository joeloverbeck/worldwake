#[derive(Clone, Debug)]
struct ScenarioCoverage {
    path: PathBuf,
    slug: String,
    def: ScenarioDef,
    statuses: Vec<FeatureStatus>,
    warnings: Vec<String>,
}

fn main() -> ExitCode {
    let args = Args::parse();
    match run(&args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("{err}");
            ExitCode::from(1)
        }
    }
}

fn run(args: &Args) -> Result<(), String> {
    let scenarios = load_all_scenarios(&scenario_dir()).map_err(|err| err.to_string())?;
    let markdown = render_markdown(&scenarios);

    if args.check {
        check_generated_output(&generated_output_path(), &markdown)?;
    } else if args.write {
        let output_path = generated_output_path();
        if let Some(parent) = output_path.parent() {
            fs::create_dir_all(parent).map_err(|err| err.to_string())?;
        }
        fs::write(&output_path, markdown).map_err(|err| err.to_string())?;
    } else {
        print!("{markdown}");
    }

    Ok(())
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap_or_else(|_| Path::new(env!("CARGO_MANIFEST_DIR")).join("../.."))
}

fn scenario_dir() -> PathBuf {
    repo_root().join("scenarios")
}

fn generated_output_path() -> PathBuf {
    repo_root().join("docs/generated/scenario-coverage.md")
}

fn relative_repo_path(path: &Path) -> &Path {
    path.strip_prefix(repo_root()).unwrap_or(path)
}

fn load_all_scenarios(dir: &Path) -> Result<Vec<ScenarioCoverage>, Box<dyn std::error::Error>> {
    let mut paths = fs::read_dir(dir)?
        .collect::<Result<Vec<_>, _>>()?
        .into_iter()
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "ron"))
        .collect::<Vec<_>>();
    paths.sort();

    let mut scenarios = Vec::with_capacity(paths.len());
    for path in paths {
        let def = load_scenario_file(&path)?;
        let slug = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .ok_or_else(|| format!("invalid scenario file name: {}", path.display()))?
            .to_owned();
        let warnings = coverage_gap_warnings(&def);
        let statuses = FEATURES
            .iter()
            .map(|feature| classify_feature(feature.id, &def))
            .collect();
        scenarios.push(ScenarioCoverage {
            path,
            slug,
            def,
            statuses,
            warnings,
        });
    }

    Ok(scenarios)
}

fn render_markdown(scenarios: &[ScenarioCoverage]) -> String {
    let mut out = String::new();
    writeln!(&mut out, "{GENERATED_NOTICE}").unwrap();
    writeln!(&mut out, "{DO_NOT_EDIT_NOTICE}").unwrap();
    writeln!(&mut out).unwrap();
    writeln!(&mut out, "# Scenario Coverage").unwrap();
    writeln!(&mut out).unwrap();
    writeln!(
        &mut out,
        "Snapshot of every `scenarios/*.ron` at HEAD. This file reports structural activation only."
    )
    .unwrap();
    writeln!(&mut out).unwrap();

    let warnings = collect_warning_rows(scenarios);
    if !warnings.is_empty() {
        writeln!(&mut out, "## Coverage Warnings").unwrap();
        writeln!(&mut out).unwrap();
        for warning in warnings {
            writeln!(&mut out, "- {warning}").unwrap();
        }
        writeln!(&mut out).unwrap();
    }

    writeln!(&mut out, "## Feature x Scenario Matrix").unwrap();
    writeln!(&mut out).unwrap();
    write!(&mut out, "| Feature |").unwrap();
    for scenario in scenarios {
        write!(&mut out, " {} |", scenario.slug).unwrap();
    }
    writeln!(&mut out).unwrap();
    write!(&mut out, "|---|").unwrap();
    for _ in scenarios {
        write!(&mut out, ":-:|").unwrap();
    }
    writeln!(&mut out).unwrap();

    for (feature_index, feature) in FEATURES.iter().enumerate() {
        write!(&mut out, "| {} |", feature.name).unwrap();
        for scenario in scenarios {
            write!(&mut out, " {} |", scenario.statuses[feature_index].cell()).unwrap();
        }
        writeln!(&mut out).unwrap();
    }

    writeln!(&mut out).unwrap();
    writeln!(
        &mut out,
        "Legend: `✅` active, `⚠` structurally present but gated inactive, `—` absent."
    )
    .unwrap();
    writeln!(&mut out).unwrap();

    writeln!(&mut out, "## Per-Scenario Detail").unwrap();
    writeln!(&mut out).unwrap();
    for scenario in scenarios {
        render_scenario_detail(&mut out, scenario);
    }

    out
}

fn render_scenario_detail(out: &mut String, scenario: &ScenarioCoverage) {
    writeln!(out, "### {}", relative_repo_path(&scenario.path).display()).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "- Seed: {}", scenario.def.seed).unwrap();
    writeln!(
        out,
        "- Agents: {}",
        control_source_summary(&scenario.def.agents)
    )
    .unwrap();
    writeln!(out, "- Places: {}", scenario.def.places.len()).unwrap();
    writeln!(
        out,
        "- Survival contract: {}",
        survival_contract_summary(scenario.def.survival_health_contract.as_ref())
    )
    .unwrap();
    writeln!(out).unwrap();

    render_feature_bucket(out, "Active features", scenario, FeatureStatus::Active);
    render_feature_bucket(
        out,
        "Present-but-inactive features",
        scenario,
        FeatureStatus::PresentInactive,
    );
    render_feature_bucket(out, "Absent features", scenario, FeatureStatus::Absent);

    writeln!(out, "**World features**").unwrap();
    writeln!(
        out,
        "- commodity_decay: {}",
        if scenario.def.commodity_decay.is_some() {
            "enabled"
        } else {
            "disabled"
        }
    )
    .unwrap();
    let concealment_places = scenario
        .def
        .places
        .iter()
        .filter_map(|place| {
            place
                .visibility_profile
                .as_ref()
                .filter(|profile| profile.base_concealment.value() > 0)
                .map(|_| place.name.as_str())
        })
        .collect::<Vec<_>>();
    writeln!(
        out,
        "- visibility_profile places: {}",
        if concealment_places.is_empty() {
            "none".to_owned()
        } else {
            concealment_places.join(", ")
        }
    )
    .unwrap();
    writeln!(out, "- facilities: {}", scenario.def.facilities.len()).unwrap();
    writeln!(
        out,
        "- resource sources: {}",
        scenario.def.resource_sources.len()
    )
    .unwrap();
    writeln!(
        out,
        "- known_recipes union: {}",
        known_recipe_union(&scenario.def)
            .into_iter()
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();
    writeln!(out).unwrap();
}

fn render_feature_bucket(
    out: &mut String,
    heading: &str,
    scenario: &ScenarioCoverage,
    target_status: FeatureStatus,
) {
    writeln!(out, "**{heading}**").unwrap();
    let features = FEATURES
        .iter()
        .zip(&scenario.statuses)
        .filter(|(_, status)| **status == target_status)
        .map(|(feature, _)| feature.name)
        .collect::<Vec<_>>();
    if features.is_empty() {
        writeln!(out, "- none").unwrap();
    } else {
        for feature in features {
            writeln!(out, "- {feature}").unwrap();
        }
    }
    writeln!(out).unwrap();
}

fn collect_warning_rows(scenarios: &[ScenarioCoverage]) -> Vec<String> {
    let mut rows = Vec::new();
    for scenario in scenarios {
        for warning in &scenario.warnings {
            rows.push(format!("{}: {warning}", scenario.slug));
        }
    }
    rows
}

fn control_source_summary(agents: &[AgentDef]) -> String {
    let mut counts = BTreeMap::<&'static str, usize>::new();
    for agent in agents {
        let key = match agent.control {
            ControlSource::Human => "Human",
            ControlSource::Ai => "Ai",
            ControlSource::None => "None",
        };
        *counts.entry(key).or_default() += 1;
    }
    counts
        .into_iter()
        .map(|(control, count)| format!("{count} {control}"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn survival_contract_summary(contract: Option<&SurvivalHealthContractDef>) -> String {
    let Some(contract) = contract else {
        return "absent".to_owned();
    };
    let families = contract
        .required_self_care_families
        .iter()
        .map(|family| format!("{family:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "max_critical {}, elevated_idle {}, families [{}]",
        contract.max_authored_critical_run_ticks,
        contract.max_idle_window_ticks_with_elevated_need,
        families
    )
}

fn known_recipe_union(def: &ScenarioDef) -> BTreeSet<String> {
    let mut recipes = BTreeSet::new();
    for agent in &def.agents {
        if let Some(known_recipes) = &agent.known_recipes {
            recipes.extend(known_recipes.iter().cloned());
        }
    }
    if recipes.is_empty() {
        recipes.insert("none".to_owned());
    }
    recipes
}

fn classify_feature(feature: FeatureId, def: &ScenarioDef) -> FeatureStatus {
    match feature {
        FeatureId::Eat => basic_need_status(def, |profile| profile.hunger_weight),
        FeatureId::Drink => basic_need_status(def, |profile| profile.thirst_weight),
        FeatureId::Sleep => {
            basic_need_status_without_recipes(def, |profile| profile.fatigue_weight)
        }
        FeatureId::Relieve => {
            basic_need_status_without_recipes(def, |profile| profile.bladder_weight)
        }
        FeatureId::Wash => basic_need_status(def, |profile| profile.dirtiness_weight),
        FeatureId::TravelPhysiology => metabolism_gate_status(def, travel_physiology_active),
        FeatureId::DriveEscalation => drive_escalation_status(def),
        FeatureId::NeedDrivenExploration => exploration_status(def),
        FeatureId::ActivationDecayPerception => perception_status(def),
        FeatureId::PlaceConcealment => place_concealment_status(def),
        FeatureId::TellPeerInfoTransfer => tell_status(def),
        FeatureId::AskAboutPerson => {
            utility_weight_status(def, |profile| profile.social_weight, true)
        }
        FeatureId::ConsultRecord => {
            utility_weight_status(def, |profile| profile.social_weight, false)
        }
        FeatureId::ObligationSatiation => optional_profile_presence_status(def, |agent| {
            agent.obligation_satiation_profile.as_ref()
        }),
        FeatureId::DiversificationCuriosity => {
            optional_profile_presence_status(def, |agent| agent.diversification_profile.as_ref())
        }
        FeatureId::ExperiencePreferences => {
            optional_profile_presence_status(def, |agent| agent.preference_profile.as_ref())
        }
        FeatureId::ProductionMultiInputRecipes => production_status(def),
        FeatureId::MerchantSelling => {
            optional_profile_presence_status(def, |agent| agent.merchandise_profile.as_ref())
        }
        FeatureId::TradeNegotiation => {
            optional_profile_presence_status(def, |agent| agent.trade_disposition.as_ref())
        }
        FeatureId::CommodityValuation => {
            optional_profile_presence_status(def, |agent| agent.commodity_valuation.as_ref())
        }
        FeatureId::SubstitutePreferences => {
            optional_profile_presence_status(def, |agent| agent.substitute_preferences.as_ref())
        }
        FeatureId::ItemDecay => {
            if def.commodity_decay.is_some() {
                FeatureStatus::Active
            } else {
                FeatureStatus::Absent
            }
        }
        FeatureId::Disposal => {
            optional_profile_presence_status(def, |agent| agent.disposal_profile.as_ref())
        }
        FeatureId::FacilityQueueContention => {
            optional_profile_presence_status(def, |agent| agent.contention_disposition.as_ref())
        }
        FeatureId::OfficesSuccessionForceClaim => {
            if def.offices.is_empty() {
                FeatureStatus::Absent
            } else {
                FeatureStatus::Active
            }
        }
        FeatureId::BanditCamps => FeatureStatus::Absent,
        FeatureId::BountyPosting => posting_status(def, |profile| profile.bounty_posting_weight),
        FeatureId::NoticePosting => posting_status(def, |profile| profile.notice_posting_weight),
        FeatureId::Theft => {
            optional_profile_presence_status(def, |agent| agent.theft_disposition.as_ref())
        }
        FeatureId::JusticeAccusation => {
            optional_profile_presence_status(def, |agent| agent.justice_disposition.as_ref())
        }
        FeatureId::ViolationInvestigation => {
            optional_profile_presence_status(def, |agent| agent.violation_disposition.as_ref())
        }
        FeatureId::Patrol => patrol_status(def),
        FeatureId::Pursuit => {
            optional_profile_presence_status(def, |agent| agent.pursuit_profile.as_ref())
        }
        FeatureId::Combat => {
            optional_profile_presence_status(def, |agent| agent.combat_profile.as_ref())
        }
        FeatureId::Escort => utility_weight_status(def, |profile| profile.care_weight, false),
        FeatureId::ReportWitness => report_witness_status(def),
        FeatureId::Search => {
            optional_profile_presence_status(def, |agent| agent.violation_disposition.as_ref())
        }
        FeatureId::StockTransport => stock_transport_status(def),
    }
}

fn basic_need_status(
    def: &ScenarioDef,
    weight: impl Fn(&UtilityProfile) -> Permille,
) -> FeatureStatus {
    let mut present = false;
    for agent in &def.agents {
        let Some(utility_profile) = agent.utility_profile.as_ref() else {
            continue;
        };
        present = true;
        let structurally_present = agent.needs.is_some()
            && agent.metabolism_profile.is_some()
            && agent.drive_thresholds.is_some()
            && agent
                .known_recipes
                .as_ref()
                .is_some_and(|recipes| !recipes.is_empty());
        if structurally_present && weight(utility_profile).value() > 0 {
            return FeatureStatus::Active;
        }
    }
    if present {
        FeatureStatus::PresentInactive
    } else {
        FeatureStatus::Absent
    }
}

