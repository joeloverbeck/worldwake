fn check_generated_output(path: &Path, expected: &str) -> Result<(), String> {
    let actual = fs::read_to_string(path)
        .map_err(|err| format!("failed to read {}: {err}", path.display()))?;
    if actual == expected {
        Ok(())
    } else {
        Err(
            "generated output drifted: rerun `cargo run -p worldwake-cli --bin scenario-coverage -- --write`"
                .to_owned(),
        )
    }
}

