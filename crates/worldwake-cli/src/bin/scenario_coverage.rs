fn optional_profile_presence_status<T>(
    def: &ScenarioDef,
    access: impl Fn(&AgentDef) -> Option<&T>,
) -> FeatureStatus {
    if def.agents.iter().any(|agent| access(agent).is_some()) {
        FeatureStatus::Active
    } else {
        FeatureStatus::Absent
    }
}

